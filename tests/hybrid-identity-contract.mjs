import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const read = file => fs.readFileSync(path.join(root, file), 'utf8');

const sql = read('supabase/migrations/202608270300_hybrid_patient_identity.sql');
const backend = read('netlify/functions/patient-identity.mts');
const helpers = read('netlify/functions/_shared/patient-identity.mjs');
const patientHtml = read('patient-card.html');
const patientJs = read('patient-card.js');
const checkinHtml = read('check-in.html');
const checkinJs = read('check-in.js');
const operationsJs = read('app.js');
const docs = read('docs/HYBRID_PATIENT_IDENTITY.md');
const productNorthStar = read('docs/PRODUCT_NORTH_STAR.md');

assert.match(sql, /^begin;/m, 'identity migration must be atomic');
assert.match(sql, /^commit;/m, 'identity migration must commit explicitly');
assert.match(sql, /create table if not exists public\.clinics/i, 'clinics must be first-class tenants');
assert.match(sql, /create table if not exists public\.clinic_memberships/i, 'clinic membership must scope staff access');
const clinicMembershipFunction = sql.match(/create or replace function public\.is_clinic_member[\s\S]*?\$\$;/i)?.[0] || '';
assert.ok(clinicMembershipFunction, 'clinic membership function must be inspectable');
assert.doesNotMatch(clinicMembershipFunction, /is_super_admin/i, 'super admin must not receive implicit cross-clinic PHI access');
assert.match(sql, /unique index[^;]+on public\.patients\(clinic_id, hn\)/i, 'HN must be unique inside a clinic rather than globally');
assert.match(sql, /next_clinic_counter\(v_clinic_id, 'patient_hn'\)/i, 'HN must be generated by a tenant-scoped database counter');
assert.match(sql, /Continue above every numeric legacy suffix[\s\S]*?on conflict \(clinic_id, counter_name\)/i, 'HN counters must be seeded above legacy values before activation');
assert.match(sql, /create or replace function public\.next_encounter_number/i, 'encounter numbers must be generated by the database');

for (const table of [
  'patient_identity_links',
  'patient_identity_link_requests',
  'patient_qr_sessions',
  'encounter_identity_verifications',
  'patient_identity_events',
  'patient_identity_rate_limits'
]) {
  assert.match(sql, new RegExp(`create table if not exists public\\.${table}`, 'i'), `${table} must exist`);
  assert.match(sql, new RegExp(`alter table public\\.${table} enable row level security`, 'i'), `${table} must have RLS enabled`);
}

assert.match(sql, /subject_hash text not null/i, 'LINE identities must be stored as keyed hashes');
assert.match(sql, /token_hash text not null/i, 'QR tokens must be stored hashed');
assert.match(sql, /display_code_hash text not null/i, 'six-digit fallback codes must be stored hashed');
assert.doesNotMatch(sql, /line_user_id|line_subject\s+text/i, 'raw LINE subject IDs must not be stored');
const qrSessionTable = sql.match(/create table if not exists public\.patient_qr_sessions[\s\S]*?\n\);/i)?.[0] || '';
assert.ok(qrSessionTable, 'patient QR session schema must be inspectable');
assert.doesNotMatch(qrSessionTable, /\btoken\s+text\b/i, 'raw QR tokens must not be stored in identity tables');
assert.match(sql, /expires_at > now\(\)/i, 'QR resolution must enforce expiry');
assert.match(sql, /used_at is null/i, 'QR resolution must reject replayed credentials');
assert.match(sql, /for update/i, 'QR confirmation must lock the one-time session');
assert.match(sql, /pg_advisory_xact_lock/i, 'six-digit code collisions must be serialized in the database');
assert.match(sql, /staff_display_code[\s\S]*?20,[\s\S]*?300/i, 'staff display-code attempts must be rate-limited');
assert.match(sql, /PATIENT_QR_LOOKUP_FAILED[\s\S]*?return;/i, 'failed six-digit lookups must commit rate-limit and non-PHI audit state');
assert.match(sql, /staff_consent_confirmed_at timestamptz not null/i, 'staff-recorded consent must be timestamped');
assert.match(sql, /subject_consent_confirmed_at timestamptz not null/i, 'LINE account-holder consent must be timestamped');

for (const rpc of [
  'complete_patient_line_link',
  'list_line_linked_patients',
  'issue_patient_qr_for_subject'
]) {
  assert.match(
    sql,
    new RegExp(`revoke all on function public\\.${rpc}\\([^;]+from public, anon, authenticated;`, 'i'),
    `${rpc} must be inaccessible to browsers`
  );
}

assert.match(sql, /create or replace function public\.confirm_patient_qr/i, 'QR check-in must use an atomic RPC');
assert.match(sql, /create or replace function public\.start_manual_patient_encounter/i, 'no-phone check-in must use an atomic RPC');
assert.match(sql, /create or replace function public\.revoke_patient_identity_link/i, 'staff must be able to revoke a LINE identity link');
assert.match(sql, /'LINE_IDENTITY_REVOKED'/i, 'identity revocation must append a lifecycle event');
assert.match(sql, /'patient_identity_links'/i, 'identity revocation must append an audit record');
assert.match(sql, /trg_patient_identity_events_append_only/i, 'identity lifecycle events must be append-only');
assert.match(sql, /trg_encounter_identity_verifications_append_only/i, 'encounter identity evidence must be append-only');
assert.match(sql, /trg_audit_logs_append_only/i, 'the canonical audit ledger must be append-only');
assert.match(sql, /v_token !~ '\^\[A-Za-z0-9_-\]\{43\}\$'/i, 'QR resolution must reject malformed opaque credentials before lookup');
assert.match(sql, /perform public\.apply_initial_encounter_intake\(v_encounter\.id, p_intake\)/g, 'both check-in paths must apply intake in the same transaction');
assert.equal((sql.match(/'PATIENT_IDENTITY_CONFIRMED'/g) || []).length >= 2, true, 'both check-in paths must record identity confirmation');
assert.equal((sql.match(/'create_verified_encounter'/g) || []).length >= 2, true, 'both check-in paths must write the canonical audit event');
assert.match(sql, /AS RESTRICTIVE/gi, 'tenant boundaries must use restrictive RLS policies');

const definerFunctions = [...sql.matchAll(/create or replace function[\s\S]*?\$\$;/gi)]
  .filter(match => /security definer/i.test(match[0]));
assert.ok(definerFunctions.length >= 10, 'identity migration should expose audited server-side operations');
for (const definition of definerFunctions) {
  assert.match(definition[0], /set search_path = (?:public|pg_catalog(?:, public, pg_temp)?)/i, 'every SECURITY DEFINER function must pin search_path');
}

assert.match(backend, /verifyLineIdToken/, 'patient backend must verify LINE tokens server-side');
assert.match(backend, /hmacSha256\(lineIdentity\.subject/, 'patient backend must HMAC the LINE subject');
assert.match(backend, /consume_patient_identity_rate_limit/, 'patient backend must enforce database-backed rate limiting');
assert.match(backend, /consumeRateLimit\(config, 'preauth', 'anonymous'/, 'patient backend must rate-limit by IP before calling LINE verification');
assert.match(backend, /allowedRequestOrigin/, 'patient backend must reject cross-origin requests');
assert.match(backend, /Cache-Control': 'no-store/, 'identity responses must never be cached');
assert.match(backend, /Date\.now\(\) \+ 90_000/, 'one-time QR credentials must expire after 90 seconds');
assert.match(backend, /attempt < 5[\s\S]*?DISPLAY_CODE_COLLISION/, 'QR issuance must retry a six-digit collision safely');
assert.match(helpers, /randomBytes\(32\)/, 'QR credentials must carry 256 bits of randomness');
assert.match(helpers, /payload: `CHANANYA:PT1:\$\{token\}`/, 'QR payload must contain only the opaque credential');
assert.doesNotMatch(helpers.match(/payload:[^\n]+/)?.[0] || '', /hn|name|patientId/i, 'QR payload must not contain PHI');
assert.match(helpers, /https:\/\/api\.line\.me\/oauth2\/v2\.1\/verify/, 'LINE ID tokens must use the official verification endpoint');

assert.doesNotMatch(`${patientHtml}\n${patientJs}`, /supabase|service[_-]?role|PATIENT_IDENTITY_HMAC_SECRET/i, 'patient browser must not receive database or HMAC secrets');
assert.doesNotMatch(patientHtml, /static\.line-scdn\.net/i, 'disabled patient pages must not load the third-party LIFF SDK');
assert.match(patientJs, /if \(!config\.enabled[\s\S]*?return;[\s\S]*?await loadLineSdk\(\)/, 'LIFF SDK must load only after the server enables the patient feature');
assert.doesNotMatch(patientJs, /localStorage|sessionStorage/, 'patient browser must not persist one-time credentials');
assert.match(patientHtml, /รหัส 6 หลัก/, 'patient card must provide a camera-independent credential');
assert.match(patientHtml, /ไม่มี(?:สมาร์ตโฟน|มือถือ)/, 'patient card must explain the no-phone path');
assert.match(patientHtml, /patient-link-consent/, 'patient must actively consent before a LINE link is claimed');
assert.match(checkinHtml, /ค้น[^<\n]*HN/i, 'staff check-in must retain HN fallback');
assert.match(checkinHtml, /guardian_attestation/, 'staff check-in must support guardian attestation');
assert.match(checkinJs, /BarcodeDetector/, 'staff mobile check-in must support camera scanning');
assert.match(checkinJs, /start_manual_patient_encounter/, 'staff check-in must use the audited manual RPC');
assert.match(checkinJs, /confirm_patient_qr/, 'staff check-in must use the audited QR RPC');
assert.match(operationsJs, /revoke_patient_identity_link/, 'staff patient management must expose audited identity revocation');
assert.match(operationsJs, /hybridDatabaseReady[\s\S]*?lineIdentityReady/, 'database HN activation and LINE service activation must be gated separately');
assert.match(read('clinical-v3.html'), /id="enc-verification-method"/, 'direct Clinical intake must record the actual identity verification method');

assert.match(docs, /Digital-first, never digital-only/i, 'product doctrine must preserve access without a phone');
assert.match(docs, /production-grade/i, 'product doctrine must preserve the commercial quality target');
assert.match(docs, /one database per clinic|isolated pilot/i, 'commercial release boundary must be explicit until all master data is tenantized');
assert.match(docs, /dedicated patient-only origin/i, 'commercial activation must isolate the patient LIFF origin from staff browser storage');
assert.match(productNorthStar, /Practitioner time first/i, 'repository product doctrine must prioritize practitioner time');
assert.match(productNorthStar, /Digital-first, never digital-only/i, 'repository product doctrine must preserve the no-phone path');
assert.match(productNorthStar, /Essential-only/i, 'repository product doctrine must reject non-essential feature growth');

console.log(`Hybrid identity contracts passed: ${definerFunctions.length} SECURITY DEFINER functions + tenant, QR, fallback, audit and browser boundaries`);
