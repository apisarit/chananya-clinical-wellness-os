import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const read = file => fs.readFileSync(path.join(root, file), 'utf8');
const migration = read('supabase/migrations/202608270400_atomic_clinical_financial_handoffs.sql');
const clinical = read('clinical-v3.js');
const clinicalHtml = read('clinical-v3.html');
const app = read('app.js');

for (const rpc of [
  'create_atomic_prescription_handoff',
  'issue_atomic_dispensing_invoice',
  'record_atomic_invoice_payment',
  'clinical_financial_handoffs_healthcheck'
]) {
  assert.match(migration, new RegExp(`create or replace function public\\.${rpc}\\b`, 'i'));
  assert.match(migration, new RegExp(`revoke all on function public\\.${rpc}\\b`, 'i'));
  assert.match(migration, new RegExp(`grant execute on function public\\.${rpc}\\b`, 'i'));
}

assert.match(migration, /^begin;/i, 'migration must begin transactionally');
assert.match(migration, /commit;\s*\n\s*select/i, 'migration must commit before verification query');
assert.ok(
  (migration.match(/security definer/gi) || []).length >= 4,
  'all RPCs must execute behind a controlled security boundary'
);
assert.ok(
  (migration.match(/set search_path = public/gi) || []).length >= 4,
  'SECURITY DEFINER functions must pin search_path'
);
assert.match(migration, /for update/gi, 'handoffs must lock authoritative records');
assert.match(migration, /IDEMPOTENCY_KEY_REUSED/, 'idempotency key reuse must fail closed');
assert.match(migration, /next_clinic_counter\(/, 'references must be generated by a server counter');
assert.match(migration, /insert into public\.audit_logs/gi, 'each committed handoff must emit audit evidence');
assert.match(migration, /revoke insert, update, delete on public\.prescriptions from authenticated/i);
assert.match(migration, /revoke insert, update, delete on public\.invoices from authenticated/i);
assert.match(migration, /revoke insert, update, delete on public\.payments from authenticated/i);
assert.match(migration, /revoke insert, update, delete on public\.patients from authenticated/i);
assert.match(migration, /revoke insert, update, delete on public\.encounters from authenticated/i);
assert.match(migration, /revoke insert, update, delete on public\.audit_logs from authenticated/i);
assert.match(migration, /revoke all on public\.clinic_state from authenticated/i);

assert.match(clinical, /rpc\('create_atomic_prescription_handoff'/);
assert.match(app, /rpc\('issue_atomic_dispensing_invoice'/);
assert.match(app, /rpc\('record_atomic_invoice_payment'/);
assert.match(clinical, /rpc\('clinical_financial_handoffs_healthcheck'/);
assert.match(app, /rpc\('clinical_financial_handoffs_healthcheck'/);
assert.match(clinicalHtml, /id="rx-unit"[^>]*readonly/);

const forbiddenDirectWrites = /\.from\(['"](?:prescriptions|prescription_items|invoices|invoice_items|payments)['"]\)\.(?:insert|update|delete|upsert)\s*\(/;
assert.doesNotMatch(clinical, forbiddenDirectWrites, 'clinical browser code must not bypass atomic handoffs');
assert.doesNotMatch(app, forbiddenDirectWrites, 'billing browser code must not bypass atomic handoffs');
assert.doesNotMatch(app, /\.from\(['"](?:patients|patient_allergies|audit_logs)['"]\)\.(?:insert|update|delete|upsert)\s*\(/, 'patient and audit writes must use trusted RPCs');
assert.doesNotMatch(clinical, /\.from\(['"]encounters['"]\)\.insert\s*\(/, 'encounter intake must use the atomic identity RPC');

console.log(
  'Atomic handoff contracts passed: server numbering, idempotency, locks, tenant roles, audit, RPC-only browser writes and fail-closed health gate'
);
